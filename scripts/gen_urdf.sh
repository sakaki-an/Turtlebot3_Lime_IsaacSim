#!/usr/bin/env bash
# Generate the plain URDF that Isaac Sim imports: assets/urdf/turtlebot3_lime.urdf
#
# 1. runs `xacro` on turtlebot3_lime_description/urdf/turtlebot3_lime.urdf.xacro inside the
#    ROS 2 Jazzy container (needs realsense2_description, which the container has)
# 2. rewrites every mesh URI (package://..., file:///opt/ros/...) into a path relative to the
#    URDF file, and copies the RealSense D435 mesh next to it - so Isaac Sim can import the
#    robot without any ROS installation.
#
# You only need this if you change the xacro files. The generated URDF is committed.
set -euo pipefail
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_DIR="$REPO_ROOT/assets/urdf"
mkdir -p "$OUT_DIR/meshes"

# --- 1. xacro -> raw URDF (inside the container) ----------------------------------
"$REPO_ROOT/docker/run_ros.sh" "cd /lime/ros2_ws && \
  colcon build --packages-select turtlebot3_lime_description --symlink-install >/dev/null && \
  source install/setup.bash && \
  xacro src/turtlebot3_lime/turtlebot3_lime_description/urdf/turtlebot3_lime.urdf.xacro \
    > /lime/assets/urdf/.turtlebot3_lime.raw.urdf && \
  cp /opt/ros/jazzy/share/realsense2_description/meshes/d435.dae /lime/assets/urdf/meshes/d435.dae"

# --- 2. make mesh paths relative ------------------------------------------------------
python3 - "$OUT_DIR" <<'EOF'
import re, sys, pathlib
out = pathlib.Path(sys.argv[1])
raw = (out / ".turtlebot3_lime.raw.urdf").read_text()
desc_rel = "../../ros2_ws/src/turtlebot3_lime/turtlebot3_lime_description/"
def fix(m):
    uri = m.group(1)
    if uri.startswith("package://turtlebot3_lime_description/"):
        return f'filename="{desc_rel}{uri.split("turtlebot3_lime_description/", 1)[1]}"'
    if uri.endswith("d435.dae"):
        return 'filename="meshes/d435.dae"'
    raise SystemExit(f"Unhandled mesh URI: {uri}")
urdf = re.sub(r'filename="([^"]+)"', fix, raw)
header = ("<!-- GENERATED by scripts/gen_urdf.sh from turtlebot3_lime.urdf.xacro - do not edit by hand.\n"
          "     Mesh paths are relative to this file so Isaac Sim can import it without ROS. -->\n")
urdf = re.sub(r'(<\?xml[^>]*\?>\s*)', r'\1' + header, urdf, count=1)
(out / "turtlebot3_lime.urdf").write_text(urdf)
(out / ".turtlebot3_lime.raw.urdf").unlink()
meshes = sorted(set(re.findall(r'filename="([^"]+)"', urdf)))
for f in meshes:
    assert (out / f).exists(), "missing mesh: " + f
print("[gen_urdf] wrote %s (%d meshes, all found)" % (out / "turtlebot3_lime.urdf", len(meshes)))
EOF
